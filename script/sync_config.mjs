// config.toml → app/.env 同步（构建前调用；事实源是 config.toml）。
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { parse } from 'smol-toml'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

let cfg = {}
try {
  cfg = parse(readFileSync(join(root, 'config.toml'), 'utf8'))
} catch (e) {
  console.error('config.toml parse failed:', e.message)
  process.exit(1)
}

const apiBase = ((cfg.server && cfg.server.api_base) || '').replace(/\/+$/, '')
if (apiBase && !/^https?:\/\//.test(apiBase)) {
  console.error(`config.toml [server].api_base must be empty or an http(s) origin, got: ${apiBase}`)
  process.exit(1)
}

const content = [
  '# generated by script/sync_config.mjs from config.toml — do not edit by hand',
  `VITE_API_BASE=${apiBase}`
].join('\n') + '\n'

writeFileSync(join(root, 'app', '.env'), content)

const localCfg = {
  enabled: Boolean(cfg.local && cfg.local.enabled),
  pgPort: Number((cfg.local && cfg.local.pg_port) || 55432),
  backendPort: Number((cfg.local && cfg.local.backend_port) || 8159),
  apiBase: apiBase || ''
}
writeFileSync(join(root, 'desktop', 'local.config.json'), JSON.stringify(localCfg, null, 2) + '\n')
console.log(`config synced: VITE_API_BASE=${apiBase || '(relative /api)'} · local.enabled=${localCfg.enabled}`)
